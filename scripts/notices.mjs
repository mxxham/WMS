#!/usr/bin/env node
// Third-party notices for the Lisensi page: every package the app ships (package.json dependencies
// and theirs), with its licence and its licence file. Writes lib/third-party-notices.json and each
// distinct licence text to public/licenses/<id>.txt (the page links to them, so it stays light);
// --stdout prints the JSON instead and writes nothing. Run `npm run notices` after adding or updating a package
// (tests/notices.test.ts fails while the file is stale). No dependencies of its own.
import { readFileSync, readdirSync, writeFileSync, existsSync, mkdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";

const root = process.cwd();
const own = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const seen = new Map(); // "name@version" -> entry
const texts = {};       // sha1 -> licence text, each distinct text once

function pkgDir(name, from) {
  try { return dirname(createRequire(join(from, "package.json")).resolve(`${name}/package.json`)); } catch { /* exports map hides it */ }
  for (let d = from; ; d = dirname(d)) {
    const p = join(d, "node_modules", name);
    if (existsSync(join(p, "package.json"))) return p;
    if (d === dirname(d)) return null;
  }
}

/** A dual licence that offers MIT is used under MIT (jszip: "MIT OR GPL-3.0-or-later"). */
function licenceOf(p) {
  let l = p.license ?? (Array.isArray(p.licenses) ? p.licenses.map((x) => x.type ?? x).join(" OR ") : null);
  if (l && typeof l === "object") l = l.type;
  if (!l) return "UNKNOWN";
  return / OR /.test(l) && /\bMIT\b/.test(l) ? "MIT" : l;
}

function licenceText(dir) {
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying|notice)([.-].*)?$/i.test(n));
  return f ? readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim() : null;
}

function walk(name, from) {
  const dir = pkgDir(name, from);
  if (!dir) return;
  const p = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const key = `${p.name}@${p.version}`;
  if (seen.has(key)) return;
  const text = licenceText(dir);
  let ref = null;
  if (text) { ref = createHash("sha1").update(text).digest("hex").slice(0, 12); texts[ref] = text; }
  const author = typeof p.author === "string" ? p.author : p.author?.name ?? null;
  seen.set(key, { name: p.name, version: p.version, license: licenceOf(p), author, text: ref, homepage: typeof p.homepage === "string" ? p.homepage : null });
  for (const d of Object.keys(p.dependencies ?? {})) walk(d, dir);
}

for (const d of Object.keys(own.dependencies ?? {})) walk(d, root);
const packages = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const out = JSON.stringify({ note: "Generated by scripts/notices.mjs. Do not edit by hand.", packages, texts }, null, 1) + "\n";

if (process.argv.includes("--stdout")) process.stdout.write(out);
else {
  writeFileSync(join(root, "lib/third-party-notices.json"), out);
  const dir = join(root, "public/licenses");
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const [id, text] of Object.entries(texts)) writeFileSync(join(dir, `${id}.txt`), text + "\n");
  console.log(`lib/third-party-notices.json: ${packages.length} packages, ${Object.keys(texts).length} distinct licence texts`); }
